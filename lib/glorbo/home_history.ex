defmodule Glorbo.HomeHistory do
  @moduledoc """
  Git-backed durable history for `~/.glorbo/` (GEP-33 Phase 1).

  This module owns the optional, opt-in git repository that lives at
  the home root. It is **derivative**: the working tree under
  `~/.glorbo/` remains the authoritative source of truth (GEP-3). Git
  records changes for diff / log / restore UX without becoming a
  second source of truth.

  Phase 1 scope:

    * `init/1` — bootstrap the repo, write `.gitignore`, stage the
      currently-tracked subset, write the initial commit.
    * `status/1` — wrap `git status --porcelain` against the home
      tree. Reports enabled/disabled + dirty paths.
    * `log/1` — wrap `git log --oneline -n N`.
    * `commit_marked/3` (Phase 2a-1) — synchronous primitive that
      stages an explicit list of paths, applies the
      tracked-scope filter, and writes one commit with kernel
      committer + actor author + sanitized GEP-33 §4.3 trailers.
      Best-effort: returns `{:error, _}` on git failure so the
      caller can decide whether to retry / warn / drop the
      commit. **No coalescer / no debouncer / no caller wiring
      yet** — those are Phase 2b and 2c.

  Out of scope here (Phase 2b+):

    * Coalesced begin/mark/flush GenServer with debounce window.
    * Watcher-fallback commits for manual edits.
    * Wiring into Router / Actions / scaffolders / restore.
    * `restore`, `show`, `diff` — read-only inspection beyond `log`.

  ## Tracked vs ignored

  Per GEP-33 §3, the repo tracks the durable, user-meaningful subset
  of `~/.glorbo/`:

    * tracked: `companies/<co>/{company.md, projects/**, channels/*.md,
      proposals/*.md, audit/*.jsonl, goals/*.md, skills/*.md,
      agents/<slug>/{AGENT.md, agent.md, SOUL.md, HEARTBEAT.md,
      memory/**, history/**}}`, plus `.gitignore` itself.
    * ignored: `.git/`, `config.md` (carries secrets),
      `providers.toml` (user-controlled `[env]` may carry provider
      API tokens — C-063), `glorbo.db*`,
      `logs/**`, `runtime/**`, `run/**`, `cache/**`, plus per-agent
      `inbox/**`, `outbox/**`, `state/**`, `workspace/**`,
      `stdout.log` (transport / scratch / runtime).

  `.gitignore` encodes the negative half so that git's own
  enumeration matches the tracked-scope rules without us having to
  walk the tree manually.

  ## Author vs committer (Phase 2)

  Phase 1 commits use whatever git env identity the daemon's user
  has — there is no marked-commit pipeline yet. Phase 2 wires the
  `Glorbo Kernel <kernel@glorbo.local>` committer + per-actor author
  identity per GEP-33 §4.2.
  """

  @gitignore """
  # Glorbo home git history — auto-generated by `glorbo history init`.
  # GEP-33 §3.2 — durable state only; secrets, derived data, and
  # transport directories are excluded.

  # Self
  /.git/

  # Secrets — config.md (key base / dashboard token) and the
  # user-controlled provider registry, whose `[env]` table may carry
  # provider API tokens (C-063). Both are denied so they never enter
  # git objects.
  /config.md
  /providers.toml

  # Derived state
  /glorbo.db
  /glorbo.db-shm
  /glorbo.db-wal

  # Logs / runtime / cache
  /logs/
  /runtime/
  /run/
  /cache/

  # Per-agent transport + scratch + stdout log
  /companies/*/agents/*/inbox/
  /companies/*/agents/*/outbox/
  /companies/*/agents/*/state/
  /companies/*/agents/*/workspace/
  /companies/*/agents/*/stdout.log

  # Retired-agent archive — once retired, an agent's subtree is
  # frozen by definition; the retire event itself is captured in
  # the audit log and (when `Agents.retire/3` is Phase-2c-wired)
  # in a single history commit. Tracking the archive's ongoing
  # filesystem state would balloon the repo with content that
  # can't change.
  /companies/*/agents/.archive/
  """

  @type init_result :: %{
          required(:repo) => Path.t(),
          required(:initial_commit) => String.t() | nil,
          required(:tracked) => non_neg_integer()
        }

  @type status_result :: %{
          required(:enabled) => boolean(),
          required(:repo) => Path.t() | nil,
          required(:dirty) => [String.t()]
        }

  @typedoc """
  Logical actor identity per GEP-33 §4.2. Becomes the commit's
  author; the committer is always `Glorbo Kernel`.
  """
  @type actor ::
          :director
          | {:agent, String.t()}
          | {:mcp, String.t()}
          | :system
          | :external

  @typedoc """
  Required metadata for `commit_marked/3`. Sanitized into
  `Glorbo-Actor`, `Glorbo-Action`, `Glorbo-Target`,
  `Glorbo-Source`, `Glorbo-Paths`, `Glorbo-Tx` trailers per
  GEP-33 §4.3 before being handed to git.
  """
  @type tx_meta :: %{
          required(:actor) => actor(),
          required(:action) => String.t(),
          required(:target) => String.t(),
          optional(:source) => String.t(),
          optional(:tx_id) => String.t()
        }

  @type commit_result :: %{
          required(:sha) => String.t(),
          required(:committed) => non_neg_integer(),
          required(:skipped) => [Path.t()]
        }

  # Sanitization — trailer values pass through these caps before
  # they reach git. The thresholds favour readable subjects + a
  # bounded git-log surface; bumps are cheap if a trailer needs
  # more room (e.g., the `Glorbo-Paths` list, which gets a wider
  # cap explicitly below).
  @max_trailer_value_len 200
  @max_paths_trailer_len 1000
  @max_actor_slug_len 64

