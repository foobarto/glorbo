defmodule GlorboWeb.BenchmarksLive do
  @moduledoc """
  Benchmark runs aggregate view — GET `/benchmarks` (GEP-26 Phase B).

  Flat table of every `benchmarks/runs/<run-id>/` directory that
  carries a valid `manifest.md`. Click-through to the detail view
  at `/benchmarks/<run-id>` for blind scoring.

  Read-only — new runs are generated by the dispatch machinery (or
  manually assembled from outputs) and surface here via the
  filesystem.
  """
  use GlorboWeb, :live_view

  import GlorboWeb.LiveHelpers, only: [base_dir: 0]

  alias Glorbo.Benchmarks
  alias GlorboWeb.Components.ChatDrawer

  @impl true
  def mount(_params, _session, socket) do
    {:ok,
     socket
     |> assign(:page_title, "Benchmarks — Glorbo")
     |> assign(:sidebar_active, :benchmarks)
     |> assign(:runs, Benchmarks.list(base: base_dir()))
     |> ChatDrawer.State.wire_drawer()}
  end

  @impl true
  def handle_event("chat_drawer_post", %{"body" => body}, socket),
    do: ChatDrawer.State.post(socket, body)

  def handle_event("refresh", _params, socket),
    do: {:noreply, assign(socket, :runs, Benchmarks.list(base: base_dir()))}

  @impl true
  def render(assigns) do
    ~H"""
    <section class="gl-view gl-benchmarks">
      <header class="gl-view__header gl-view__header--split">
        <div>
          <h1 class="gl-heading gl-heading--display">
            <span class="gl-muted">benchmarks /</span> runs
          </h1>
          <p class="gl-overview__quote">
            // Cross-provider A/B runs (GEP-26 Phase B). Blind-score from the detail view.
          </p>
        </div>
        <div>
          <button type="button" class="gl-btn" phx-click="refresh">↻ refresh</button>
        </div>
      </header>

      <div :if={@runs == []} class="gl-empty">
        No benchmark runs on disk yet. Expected shape:
        <code>~/.glorbo/benchmarks/runs/&lt;run-id&gt;/manifest.md</code>
      </div>

      <table :if={@runs != []} class="gl-table gl-benchmarks__table">
        <thead>
          <tr>
            <th>run</th>
            <th>template</th>
            <th>task</th>
            <th>providers</th>
            <th>status</th>
            <th>started</th>
          </tr>
        </thead>
        <tbody>
          <tr :for={r <- @runs}>
            <td class="gl-tabular">
              <.link navigate={~p"/benchmarks/#{r.run_id}"}>{r.run_id}</.link>
            </td>
            <td>{r.template || "—"}</td>
            <td class="gl-tabular">{r.task || "—"}</td>
            <td>
              <span :for={p <- r.providers} class="gl-tag">{p}</span>
            </td>
            <td>
              <span class={["gl-pill", status_pill_class(r.status)]}>{r.status || "—"}</span>
            </td>
            <td class="gl-tabular gl-muted">{r.started_at || "—"}</td>
          </tr>
        </tbody>
      </table>
    </section>
    """
  end

  defp status_pill_class("scored"), do: "gl-pill--alive"
  defp status_pill_class("completed"), do: "gl-pill--alive"
  defp status_pill_class("in-progress"), do: "gl-pill--info"
  defp status_pill_class("queued"), do: "gl-pill--info"
  defp status_pill_class("failed"), do: "gl-pill--stop"
  defp status_pill_class(_), do: "gl-pill--info"
end
